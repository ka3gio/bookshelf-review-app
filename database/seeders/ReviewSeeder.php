        $userIds = User::orderBy('id')->pluck('id')->values();

        if ($userIds->isEmpty()) {
            return;
        }

        foreach (self::REVIEWS_BY_BOOK_ID as $bookId => $reviews) {
            $book = Book::find($bookId);

            if ($book === null) {
                continue;
            }

            foreach ($reviews as [$rating, $comment]) {
                Review::create([
                    'book_id' => $book->id,
                    'user_id' => $userIds->random(),
                    'rating' => $rating,
                    'comment' => $comment,
                ]);
            }
        }
